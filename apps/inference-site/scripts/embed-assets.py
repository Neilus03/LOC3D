"""Bundle the reviewed Delimit3D UI into the dependency-free Worker artifact."""
import json
from pathlib import Path
import sys
root = Path(__file__).resolve().parent.parent
source = Path(sys.argv[1]) if len(sys.argv) > 1 else root / "ui"
assets = {}
for name, content_type, url in [("index.html", "text/html; charset=utf-8", "/"), ("style.css", "text/css; charset=utf-8", "/static/style.css"), ("app.mjs", "text/javascript; charset=utf-8", "/static/app.mjs"), ("viewer.mjs", "text/javascript; charset=utf-8", "/static/viewer.mjs")]:
    body = (source / name).read_text()
    if name == "index.html":
        body = body.replace("Local session", "Private GPU session").replace("Checking the local model registry.", "Checking the connected GPU models.")
    assets[url] = {"body": body, "type": content_type}
p = root / "worker/index.js"
s = p.read_text().split("// ASSET_BUNDLE_START")[0]
p.write_text(s + "// ASSET_BUNDLE_START — generated by scripts/embed-assets.py\nconst ASSETS = " + json.dumps(assets, ensure_ascii=False) + ";\n")
